class Trip {
  final String city;
  final String route;
  final String company;
  final int price;
  final String from;
  final String to;
  final String departure;
  final int availableSeats;
  final int totalSeats;

  Trip({
    required this.city,
    required this.route,
    required this.company,
    required this.price,
    required this.from,
    required this.to,
    required this.departure,
    required this.availableSeats,
    required this.totalSeats,
  });
}
